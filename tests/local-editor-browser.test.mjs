import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir,readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createRequire} from 'node:module';
import {startEditor} from '../tools/editor/server.mts';
import {editorContent} from '../tools/editor/content.mts';
const require=createRequire(import.meta.url);
const {loadPlaywright,browserLaunchOptions}=require('./helpers/browser-runtime.js');

test('desktop editor saves Chinese, reloads it, preserves English, restores history and guards unsaved changes',async()=>{
 const draftRoot=await mkdtemp(join(tmpdir(),'melone-editor-browser-'));
 const server=await startEditor({port:0,draftRoot});
 const {chromium}=loadPlaywright({from:import.meta.filename});
 const browser=await chromium.launch(browserLaunchOptions(chromium.executablePath()));
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const requests=[];page.on('request',request=>requests.push(request.url()));
 try{
  await page.goto(server.url);
  await page.locator('#page:not([disabled])').waitFor();
  assert.equal(await page.locator('#page option').count(),103);
  await page.fill('#page-search','不会存在的网页名称');
  assert.match(await page.locator('#page-count').innerText(),/匹配 0/);
  await page.click('#clear-search');
  assert.equal(await page.inputValue('#page-search'),'');
  await page.locator('#page').focus();await page.keyboard.press('ArrowDown');await page.keyboard.press('Escape');
  await page.selectOption('#page','about.html');
  await page.waitForFunction(()=>document.title.includes('about.html'));
  const model=editorContent('about.html'),field=model.fields.find(field=>field.kind==='text'&&!field.locked);
  await page.selectOption('#field',field.id);
  const english=await page.locator('#original').innerText();
  await page.fill('#translation','网络失败仍保留的草稿');
  await page.route('**/__editor/api/draft/*',route=>route.request().method()==='PUT'?route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'测试：服务暂不可用'})}):route.continue());
  await page.click('#save');
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('当前文字已保留'));
  assert.equal(await page.inputValue('#translation'),'网络失败仍保留的草稿');
  await page.unroute('**/__editor/api/draft/*');
  await page.locator('#translation').dispatchEvent('compositionstart');
  assert.equal(await page.locator('#save').isDisabled(),true);
  await page.locator('#translation').dispatchEvent('compositionend');
  await page.fill('#translation','仅保存在测试草稿中的中文说明');
  await page.click('#save');
  await page.waitForFunction(()=>document.querySelector('#save').disabled&&!document.querySelector('#save').getAttribute('aria-busy').includes('true'));
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('保存'));
  await page.reload();await page.waitForFunction(()=>document.title.includes('about.html'));
  await page.selectOption('#field',field.id);
  assert.equal(await page.inputValue('#translation'),'仅保存在测试草稿中的中文说明');
  assert.equal(await page.locator('#original').innerText(),english);
  await page.fill('#translation','第二次仅测试修订');await page.click('#save');
  await page.waitForFunction(()=>document.querySelector('#revision').textContent.includes('修订 2'));
  await page.locator('details').filter({has:page.locator('#history')}).locator('summary').click();
  await page.selectOption('#history','1');await page.click('#restore');
  await page.locator('#confirm-action[open]').waitFor();await page.click('#commit-action');
  await page.waitForFunction(()=>document.querySelector('#revision').textContent.includes('修订 3'));
  await page.selectOption('#field',field.id);
  assert.equal(await page.inputValue('#translation'),'仅保存在测试草稿中的中文说明');
  await page.fill('#translation','尚未保存的测试');await page.selectOption('#page','index.html');
  await page.locator('#unsaved[open]').waitFor();await page.click('#keep');
  assert.equal(await page.inputValue('#translation'),'尚未保存的测试');
  await page.selectOption('#page','index.html');await page.locator('#unsaved[open]').waitFor();await page.click('#discard');
  await page.waitForFunction(()=>document.title.includes('index.html'));
  const preview=page.frameLocator('#preview');
  const clickField=preview.locator('h1 [data-editor-field]').first();
  const clickedId=await clickField.getAttribute('data-editor-field');
  await clickField.click();
  await page.waitForFunction(id=>document.querySelector('#field').value===id,clickedId);
  assert.equal(await page.locator('#translation').evaluate(node=>node===document.activeElement),true);
  await page.selectOption('#preview-language','en-AU');
  await preview.locator('html[lang="en-AU"]').waitFor();
  assert.equal(await preview.locator('[data-editor-field]').count(),0);
  await page.selectOption('#preview-language','zh-Hans');
  await preview.locator('[data-editor-field]').first().waitFor();
  const report=join(import.meta.dirname,'../../reports/2026-10-19-local-editor');await mkdir(report,{recursive:true});
  await page.screenshot({path:join(report,'editor-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:900});await page.screenshot({path:join(report,'editor-mobile.png'),fullPage:true});
  assert.equal(await preview.locator('#primary-nav').isHidden(),true);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  assert.deepEqual(errors,[]);
  assert.ok(requests.every(url=>new URL(url).origin===new URL(server.url).origin));
  assert.ok(!requests.some(url=>url.includes('/api/contact')));
  const actual=JSON.parse(await readFile(join(draftRoot,'about.html.json'),'utf8'));
  assert.equal(actual.revision,3);assert.equal(actual.changes[field.id],'仅保存在测试草稿中的中文说明');
 }finally{await browser.close();await server.close();await rm(draftRoot,{recursive:true,force:true});}
});
